// Generates styles/tokens.css from styles/tokens.json. Run: npm run tokens
import { readFileSync, writeFileSync } from "node:fs"
import { hexToHsl } from "./hsl.mjs"

const tokens = JSON.parse(readFileSync(new URL("../styles/tokens.json", import.meta.url), "utf8"))

const block = (selector, palette, extra = "") =>
  `${selector} {\n${Object.entries(palette)
    .map(([k, v]) => `  --${k}: ${hexToHsl(v)}; /* ${v} */`)
    .join("\n")}\n${extra}}\n`

const css = `/* GENERATED by scripts/build-tokens.mjs from styles/tokens.json. Do not edit. */
/* html carries .dark for the legacy back-office; the CRM shell re-declares .light. */

${block(":root,\n.light", tokens.light, `  --radius: ${tokens.radius};\n`)}
${block(".dark", tokens.dark)}`

writeFileSync(new URL("../styles/tokens.css", import.meta.url), css)
console.log("styles/tokens.css written")
