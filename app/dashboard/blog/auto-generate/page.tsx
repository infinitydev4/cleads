"use client"

import { useState, useEffect } from "react"
import { Tabs, TabsContent, TabsList, TabsTrigger } from "@/components/ui/tabs"
import { Button } from "@/components/ui/button"
import { 
  FileText, 
  PlusCircle, 
  RotateCcw, 
  Calendar, 
  Sparkles, 
  Rss, 
  ArrowLeft 
} from "lucide-react"
import { AutoArticleGenerator } from "@/components/blog/auto-article-generator"
import { ScheduleList } from "@/components/blog/schedule-list"
import { useRouter } from "next/navigation"
import { toast } from "sonner"

export default function AutoGeneratePage() {
  const [loading, setLoading] = useState(false)
  const [activeTab, setActiveTab] = useState("schedules")
  const router = useRouter()

  // Gérer l'article généré
  const handleGenerated = async (article: any) => {
    try {
      setLoading(true)
      
      // Rediriger vers le formulaire de création d'article avec les données pré-remplies
      router.push(`/dashboard/blog/new?autoGenerated=true&title=${encodeURIComponent(article.title)}`)
      
      // Stocker l'article généré dans localStorage pour le récupérer sur la page de création
      localStorage.setItem("autoGeneratedArticle", JSON.stringify(article))
      
      toast.success("Article généré avec succès!")
    } catch (error) {
      console.error("Erreur lors du traitement de l'article généré:", error)
      toast.error("Erreur lors du traitement de l'article")
    } finally {
      setLoading(false)
    }
  }

  // Fonction pour rafraîchir la liste des planifications
  const refreshSchedules = () => {
    setActiveTab("schedules")
    // La ScheduleList gère son propre rechargement
  }

  return (
    <div className="p-6 lg:p-8">
      {/* En-tête */}
      <div className="flex flex-col md:flex-row md:items-center md:justify-between mb-8">
        <div className="flex items-center gap-3">
          <Button 
            variant="ghost" 
            size="icon"
            onClick={() => router.push("/dashboard/blog")}
            className="h-8 w-8"
          >
            <ArrowLeft className="h-4 w-4" />
          </Button>
          <div>
            <h1 className="text-2xl font-bold text-white">Génération automatique d'articles</h1>
            <p className="text-gray-400">Créez du contenu optimisé pour le SEO basé sur les tendances actuelles</p>
          </div>
        </div>
        
        <div className="flex items-center gap-3 mt-4 md:mt-0">
          <Button
            variant="outline"
            size="sm"
            onClick={refreshSchedules}
            className="text-gray-400 h-8"
          >
            <RotateCcw className="h-3.5 w-3.5 mr-1" />
            Actualiser
          </Button>
          
          <Button 
            size="sm"
            onClick={() => setActiveTab("generate")}
            className="bg-[#BFFF00] text-black hover:bg-[#BFFF00]/90 h-8"
          >
            <Sparkles className="h-3.5 w-3.5 mr-1" />
            Nouvelle génération
          </Button>
        </div>
      </div>
      
      {/* Onglets */}
      <Tabs 
        defaultValue="schedules" 
        value={activeTab}
        onValueChange={setActiveTab}
        className="w-full"
      >
        <TabsList className="grid w-full grid-cols-2 mb-8">
          <TabsTrigger value="schedules" className="flex items-center gap-2">
            <Calendar className="h-4 w-4" />
            Planifications actives
          </TabsTrigger>
          <TabsTrigger value="generate" className="flex items-center gap-2">
            <Rss className="h-4 w-4" />
            Générer un article
          </TabsTrigger>
        </TabsList>
        
        {/* Tab de planifications */}
        <TabsContent value="schedules" className="mt-0">
          <ScheduleList />
        </TabsContent>
        
        {/* Tab de génération d'article */}
        <TabsContent value="generate" className="mt-0">
          <AutoArticleGenerator onGenerated={handleGenerated} />
        </TabsContent>
      </Tabs>
    </div>
  )
} 